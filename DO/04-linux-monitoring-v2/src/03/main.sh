#!/bin/bash
source ./log_deleter.sh
source ./time_deleter.sh
source ./mask_deleter.sh
source ./validator.sh

info(){
    echo "Нужно передать минимум 1 аргумент (1, 2 или 3). При желании можно указать также второй и третий параметры соответствующий первому"
    echo "1 - Очистка по лог-файлу (второй параметр: путь к лог-файлу)"
    echo "2 - Очистка по дате и времени(второй параметр: начальное значение временного диапазона (в формате ГГГГ-ММ-ДД ЧЧ:ММ)), третий параметр: конечно значение временного диапазона (в формате ГГГГ-ММ-ДД ЧЧ:ММ)"
    echo "3 - Очистка по маске имени (второй параметр: маска (буквы используемые при генерации))"    
}
check_gt $# 3 || { info; exit 1; }
check_zero $@ || { info; exit 1; }

choose="$1"
if [  -z $choose ]; then
    info
    read -p "Введите номер вашего выбора алгоритма очистки: " choose
fi

arg2="${2:-}"
arg3="${3:-}"


case "$choose" in
    1) echo "Выбрана очистка по лог-файлу"
    log_deleter "$arg2"
    ;;
    2) echo "Выбрана очистка по дате и времени"
    time_deleter "$arg2" "$arg3"
    ;;
    3) echo "Выбрана очистка по маске"
    mask_deleter "$arg2"
    ;;
    *)
    info
    exit 1
    ;;

esac