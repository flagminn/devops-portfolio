#!/bin/bash

# ==============================================================================
# РАСШИФРОВКА ИСПОЛЬЗУЕМЫХ HTTP-КОДОВ ОТВЕТА (RFC 9110)
# ==============================================================================
# 2xx Success (Успешно)
# 200 OK              - Запрос выполнен успешно (стандарт для GET/PUT).
# 201 Created         - Запрос выполнен, и создан новый ресурс (часто для POST).
#
# 4xx Client Error (Ошибка клиента)
# 400 Bad Request     - Сервер не понял запрос из-за неверного синтаксиса.
# 401 Unauthorized    - Требуется аутентификация (логин/пароль).
# 403 Forbidden       - Доступ запрещен (даже если пользователь залогинен).
# 404 Not Found       - Ресурс не найден (неверный URL).
#
# 5xx Server Error (Ошибка сервера)
# 500 Internal Error  - Общая ошибка сервера (что-то сломалось внутри).
# 501 Not Implemented - Сервер не поддерживает метод запроса (например, PATCH).
# 502 Bad Gateway     - Сервер (прокси) получил недопустимый ответ от вышестоящего сервера.
# 503 Service Unavail - Сервер временно не может обрабатывать запросы (перегрузка/ТО).
# ==============================================================================
